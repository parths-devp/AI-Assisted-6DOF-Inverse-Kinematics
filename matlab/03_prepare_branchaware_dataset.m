load("ik_dataset_branchaware.mat");
N=size(X,1);
rng(42);
idx=randperm(N);
X=X(idx,:);
Y=Y(idx,:);
NTrain=floor(0.70*N);
NVal=floor(0.15*N);
XTrain=X(1:NTrain,:);
YTrain=Y(1:NTrain,:);
XVal=X(NTrain+1:NTrain+NVal,:);
YVal=Y(NTrain+1:NTrain+NVal,:);
XTest=X(NTrain+NVal+1:end,:);
YTest=Y(NTrain+NVal+1:end,:);
XMean=mean(XTrain,1);
XStd=std(XTrain,0,1);
YMean=mean(YTrain,1);
YStd=std(YTrain,0,1);
XStd(XStd==0)=1;
YStd(YStd==0)=1;
XTrainNorm=(XTrain-XMean)./XStd;
XValNorm=(XVal-XMean)./XStd;
XTestNorm=(XTest-XMean)./XStd;
YTrainNorm=(YTrain-YMean)./YStd;
YValNorm=(YVal-YMean)./YStd;
YTestNorm=(YTest-YMean)./YStd;
save("ik_dataset_branchaware_prepared.mat","XTrain","YTrain","XVal","YVal","XTest","YTest","XMean","XStd","YMean","YStd","XTrainNorm","XValNorm","XTestNorm","YTrainNorm","YValNorm","YTestNorm");