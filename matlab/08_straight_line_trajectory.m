clear; clc; close all;
load("ik_dataset_branchaware_prepared.mat");
load("ik_branchaware_network.mat");
robot=importrobot("../robot/base_fixed.urdf");
robot.DataFormat="struct";
ik=inverseKinematics("RigidBodyTree",robot);
weights=[1 1 1 1 1 1];
pStart=[-0.50 -0.10 0.60];
pEnd=[-0.40 0.00 0.60];
N=200;
trajectory=[linspace(pStart(1),pEnd(1),N)',linspace(pStart(2),pEnd(2),N)',linspace(pStart(3),pEnd(3),N)'];
orientation=eul2tform([pi 0.9599 0]);
currentConfig=homeConfiguration(robot);
previousQ=[currentConfig(1:6).JointPosition];
actualPosition=zeros(N,3);
positionErrorAI=zeros(N,1);
positionErrorHybrid=zeros(N,1);
aiTime=zeros(N,1);
ikTime=zeros(N,1);
for i=1:N
    targetPosition=trajectory(i,:);
    input=[targetPosition,tform2quat(orientation),previousQ];
    tic;
    inputNorm=(input-XMean)./XStd;
    predictionNorm=predict(net,inputNorm);
    aiTime(i)=toc;
    prediction=double(predictionNorm.*YStd+YMean);
    prediction=max(prediction,-pi+1e-5);
    prediction=min(prediction,pi-1e-5);
    aiConfig=homeConfiguration(robot);
    for j=1:6
        aiConfig(j).JointPosition=prediction(j);
    end
    TAI=getTransform(robot,aiConfig,"jaw6_1",robot.BaseName);
    positionErrorAI(i)=norm(tform2trvec(TAI)-targetPosition);
    targetPose=trvec2tform(targetPosition)*orientation;
    tic;
    [solution,~]=ik("jaw6_1",targetPose,weights,aiConfig);
    ikTime(i)=toc;
    T=getTransform(robot,solution,"jaw6_1",robot.BaseName);
    actualPosition(i,:)=tform2trvec(T);
    positionErrorHybrid(i)=norm(actualPosition(i,:)-targetPosition);
    previousQ=[solution(1:6).JointPosition];
end
fprintf("AI only mean: %.2f mm\n",mean(positionErrorAI)*1000);
fprintf("AI only median: %.2f mm\n",median(positionErrorAI)*1000);
fprintf("AI only max: %.2f mm\n",max(positionErrorAI)*1000);
fprintf("Hybrid mean: %.4f mm\n",mean(positionErrorHybrid)*1000);
fprintf("Hybrid max: %.4f mm\n",max(positionErrorHybrid)*1000);
fprintf("AI mean time: %.4f ms\n",mean(aiTime)*1000);
fprintf("IK mean time: %.4f ms\n",mean(ikTime)*1000);
fprintf("Total mean time: %.4f ms\n",mean(aiTime+ikTime)*1000);
save("straight_line_results.mat","trajectory","actualPosition","positionErrorAI","positionErrorHybrid","aiTime","ikTime");
figure;
plot3(trajectory(:,1),trajectory(:,2),trajectory(:,3),"k--","LineWidth",1.5);
hold on;
plot3(actualPosition(:,1),actualPosition(:,2),actualPosition(:,3),"b-","LineWidth",2);
grid on; axis equal; view(3);
xlabel("X (m)"); ylabel("Y (m)"); zlabel("Z (m)");
title("Target and Actual End-Effector Path");